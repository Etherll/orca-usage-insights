// Regenerates src/core/catalog-data.mjs, the bundled price table, from a LiteLLM price snapshot and,
// optionally, a models.dev snapshot for the OpenCode channels.
// Usage: node scripts/prices.mjs <litellm.json> [modelsdev.json] [--write]
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { bundledSubset, inBundleScope, parseLiteLLM, parseModelsDev, today } from '../src/core/price-sources.mjs'

const OPENCODE = ['opencode', 'opencode-go']
const OUT = fileURLToPath(new URL('../src/core/catalog-data.mjs', import.meta.url))
const args = process.argv.slice(2)
const files = args.filter((arg) => !arg.startsWith('--'))
const write = args.includes('--write')
const unknown = args.filter((arg) => arg.startsWith('--') && arg !== '--write')

if (files.length === 0 || files.length > 2 || unknown.length) {
  console.error('usage: node scripts/prices.mjs <litellm.json> [modelsdev.json] [--write]')
  process.exit(2)
}

const asOf = today()
const lite = parseLiteLLM(JSON.parse(readFileSync(files[0], 'utf8')), { asOf, source: 'litellm' })
// A bundled model without a complete price is left out, never guessed: the plugin shows it as unpriced.
const skipped = lite.errors.filter(inBundleScope)
for (const e of skipped) console.error(`skipped ${e.id}: ${e.reason}`)

const dev = files[1]
  ? parseModelsDev(JSON.parse(readFileSync(files[1], 'utf8')), { asOf, providers: OPENCODE })
  : { entries: [], errors: [] }
if (!files[1]) console.error('no models.dev file: OpenCode prices will not be bundled')

const bundled = [...bundledSubset(lite.entries), ...dev.entries].sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0))
const next = render(bundled)
if (write) {
  writeFileSync(OUT, next)
  console.log(`Wrote ${bundled.length} entries to ${OUT}`)
} else {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
  const diff = lineDiff(current.split('\n'), next.split('\n'))
  console.log(diff.length ? diff.join('\n') : 'no changes')
}

function render(models) {
  const lines = [
    '// Generated by scripts/prices.mjs from LiteLLM and models.dev price snapshots. Do not edit by hand.',
    '// USD per 1M tokens. OpenCode model ids are qualified by channel (opencode/ or opencode-go/).',
    '',
    'export const BUNDLED = [',
  ]
  for (const e of models) {
    lines.push('  {')
    lines.push(`    id: ${lit(e.id)},`)
    lines.push(`    provider: ${lit(e.provider)},`)
    lines.push(`    aliases: ${lit(e.aliases)},`)
    lines.push(`    input: ${lit(e.input)},`)
    lines.push(`    output: ${lit(e.output)},`)
    lines.push(`    cacheRead: ${lit(e.cacheRead)},`)
    lines.push(`    cacheWrite: ${lit(e.cacheWrite)},`)
    if (e.tiers) {
      lines.push('    tiers: [')
      for (const tier of e.tiers) lines.push(`      ${lit(tier)},`)
      lines.push('    ],')
    }
    lines.push(`    contextWindow: ${lit(e.contextWindow)},`)
    lines.push(`    source: ${lit(e.source)},`)
    lines.push(`    asOf: ${lit(e.asOf)},`)
    lines.push('  },')
  }
  lines.push('];', '')
  return lines.join('\n')
}

function lit(value) {
  if (value === null) return 'null'
  if (typeof value === 'number') return String(value)
  if (typeof value === 'string') return `'${value.replace(/[\\']/g, '\\$&')}'`
  if (Array.isArray(value)) return `[${value.map(lit).join(', ')}]`
  const fields = Object.entries(value).map(([key, v]) => `${/^[A-Za-z_$][\w$]*$/.test(key) ? key : lit(key)}: ${lit(v)}`)
  return fields.length ? `{ ${fields.join(', ')} }` : '{}'
}

function lineDiff(a, b) {
  const n = a.length
  const m = b.length
  const best = Array.from({ length: n + 1 }, () => new Uint32Array(m + 1))
  for (let i = n - 1; i >= 0; i--) {
    for (let j = m - 1; j >= 0; j--) {
      best[i][j] = a[i] === b[j] ? best[i + 1][j + 1] + 1 : Math.max(best[i + 1][j], best[i][j + 1])
    }
  }
  const out = []
  let i = 0
  let j = 0
  while (i < n && j < m) {
    if (a[i] === b[j]) {
      i++
      j++
    } else if (best[i + 1][j] >= best[i][j + 1]) {
      out.push(`- ${a[i++]}`)
    } else {
      out.push(`+ ${b[j++]}`)
    }
  }
  while (i < n) out.push(`- ${a[i++]}`)
  while (j < m) out.push(`+ ${b[j++]}`)
  return out
}
